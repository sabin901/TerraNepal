// Run with the bundled Node runtime and LAB_PLAYWRIGHT_PATH pointing to Playwright.
const {chromium}=require(process.env.LAB_PLAYWRIGHT_PATH||'playwright');
const fs=require('fs');const path=require('path');
const base=process.env.LAB_TEST_URL||'http://127.0.0.1:8766';
const out=path.join(__dirname,'reports');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const results=[];
 try{
  await page.goto(base,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:/See the signals/}).waitFor();
  await page.screenshot({path:path.join(out,'overview-desktop.png'),fullPage:true});
  results.push('overview rendered');
  await page.locator('nav a[href="#forecast"]').click();
  await page.getByRole('heading',{name:'Look ahead. See the uncertainty.'}).waitFor();
  await page.locator('#analytics-results table').waitFor();
  await page.getByRole('button',{name:'Pokhara',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-place="pokhara"]')?.getAttribute('aria-pressed')==='true');
  await page.locator('#analytics-results table').waitFor();
  await page.locator('[data-weather-hours="72"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-weather-hours="72"]')?.getAttribute('aria-pressed')==='true');
  await page.locator('#analytics-results table').waitFor();
  if(await page.locator('[data-weather-hours="72"]').getAttribute('aria-pressed')!=='true')throw Error('Forecast window control failed');
  await page.screenshot({path:path.join(out,'forecast-desktop.png'),fullPage:true});
  await Promise.all([page.waitForResponse(r=>r.url().includes('/api/analytics?')&&r.url().includes('horizon=30')),page.locator('#forecast-horizon').selectOption('30')]);
  await Promise.all([page.waitForResponse(r=>r.url().includes('/api/analytics?')&&r.url().includes('id=268')),page.locator('#forecast-station').selectOption('268')]);
  await page.locator('#analytics-results table').waitFor();
  results.push('live weather, city and 72-hour controls, river model and horizon controls');
  await page.locator('nav a[href="#quality"]').click();
  await page.getByRole('heading',{name:'Evidence health',exact:true}).waitFor();
  await page.locator('.audit-table tbody tr').first().waitFor();
  await page.getByRole('heading',{name:'Prospective prediction ledger'}).waitFor();
  results.push('station quality audit and prospective ledger');

  await page.locator('nav a[href="#incidents"]').click();
  await page.locator('#year').selectOption('2024');
  await page.locator('#incident-results').getByText('414 matching reports',{exact:true}).waitFor();
  await page.locator('#district').selectOption('Kathmandu');
  await page.waitForFunction(()=>!document.querySelector('#incident-results')?.classList.contains('loading'));
  const csv=await page.locator('#csv').getAttribute('href');
  const download=await page.request.get(base+csv);
  if(download.status()!==200||!(await download.text()).includes('incident_id'))throw Error('CSV failed');
  results.push('incident filters and CSV');
  await page.locator('nav a[href="#rivers"]').click();
  await page.locator('#cutoff').waitFor();
  await page.locator('#horizon').selectOption('30');
  await page.waitForFunction(()=>document.querySelector('#river-results')?.textContent.includes('Retrospective baseline check'));
  await page.locator('#cutoff').fill('0');await page.locator('#cutoff').dispatchEvent('change');
  await page.waitForTimeout(500);
  await page.locator('#known').check();
  await page.waitForFunction(()=>document.querySelector('#river-results')?.textContent.includes('No measurements meet'));
  await page.screenshot({path:path.join(out,'river-replay.png'),fullPage:true});
  results.push('river horizon, historical cutoff, and strict replay');
  await page.locator('nav a[href="#sources"]').click();
  await page.getByRole('heading',{name:'Know what the data can tell you.'}).waitFor();
  await page.getByRole('heading',{name:'Source messages',exact:true}).waitFor();
  results.push('source coverage and messages');
  await page.locator('nav a[href="#actions"]').click();
  const testTitle='Browser verification — '+Date.now();
  await page.locator('#action-title').fill(testTitle);
  await page.locator('#action-place').fill('Test only');
  await page.locator('#action-notes').fill('Not an actual response outcome.');
  await page.getByRole('button',{name:'Save action'}).click();
  await page.getByRole('heading',{name:testTitle}).last().waitFor();
  await page.locator('.action-card').filter({has:page.getByRole('heading',{name:testTitle})}).locator('[data-action]').selectOption('completed');
  await page.waitForTimeout(300);
  await page.reload({waitUntil:'networkidle'});
  if(await page.locator('.action-card').filter({has:page.getByRole('heading',{name:testTitle})}).locator('[data-action]').inputValue()!=='completed')throw Error('State did not persist');
  results.push('isolated action creation, status edit, reload persistence');
  await page.setViewportSize({width:390,height:844});
  await page.locator('nav a[href="#overview"]').click();
  await page.getByRole('heading',{name:/See the signals/}).waitFor();
  await page.screenshot({path:path.join(out,'overview-mobile.png'),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Mobile horizontal overflow');
  results.push('mobile layout without page overflow');
  await page.locator('nav a[href="#forecast"]').click();
  await page.locator('#analytics-results table').waitFor();
  await page.screenshot({path:path.join(out,'forecast-mobile.png'),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Forecast mobile overflow');
  await page.locator('nav a[href="#quality"]').click();
  await page.locator('.audit-table tbody tr').first().waitFor();
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Audit mobile overflow');
  results.push('forecast and evidence audit mobile layouts');
  const actualWeather=await (await page.request.get(base+'/api/weather')).json();
  for(const place of actualWeather.places){
   place.sources[0]={...place.sources[0],state:'missing',points:[],windows:{},fetched_at:null,url:null,latest_attempt:{status:'error'}};
   place.model_difference_mm={'24':null,'48':null,'72':null};
  }
  await page.route('**/api/weather',route=>route.fulfill({json:actualWeather}));
  await page.locator('nav a[href="#forecast"]').click();
  await page.locator('#analytics-results table').waitFor();
  await page.getByText('1/2 models with complete, recent windows',{exact:true}).waitFor();
  await page.getByRole('img',{name:'Hourly precipitation forecast comparison in millimeters'}).waitFor();
  if((await page.locator('.weather-chart').innerHTML()).includes('NaN'))throw Error('Missing model produced invalid chart coordinates');
  await page.unroute('**/api/weather');
  results.push('missing first weather model retains second-model chart with incomplete coverage clearly labeled');


  await page.context().setOffline(true);
  await page.locator('nav a[href="#incidents"]').click();
  await page.locator('#error').waitFor({state:'visible'});
  await page.context().setOffline(false);
  await page.reload({waitUntil:'networkidle'});
  await page.locator('#incident-results table').waitFor();
  results.push('network error visible and recovery on reload');
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(out,'browser-check.json'),JSON.stringify({checked_at:new Date().toISOString(),base,results,errors},null,2));
  console.log(JSON.stringify({results,errors},null,2));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
